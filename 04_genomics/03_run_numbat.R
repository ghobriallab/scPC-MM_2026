#!/usr/bin/env Rscript
# ============================================================================
# Purpose:      Numbat on one tumor (Methods, Copy number variant detection): reads the merged count matrix
#               (Read10X_h5), keeps the cells listed in --barcodes when that file exists, reads the merged allele table
#               and runs run_numbat (genome hg38; reference expression: Numbat's ref_hca, or the RDS file given with
#               --refexpr; plot TRUE). Numbat parameters are command-line options; the defaults of this script are
#               min_cells 50 (--mincell), tau 0.3 (--tau), t 1e-5 (--tp), max_iter 2 (--maxiter), min_LLR 5 (--minllr),
#               init_k 2 (--initk), max_entropy 0.5 (--maxentropy), gamma 20 (--gamma), min_depth 0 (--mindepth),
#               ncores 8 (--ncores).
# Inputs:       --countmat: merged 10x HDF5 count matrix of the tumor (01_combine_library_counts.py).
#               --alleledf: merged allele table of the tumor (02_combine_library_alleles.py).
#               --barcodes (optional): cell barcodes to analyze, one per line.
# Outputs:      The Numbat output folder --outdir, one per tumor (folder name <tumor_name>). Later steps read
#               segs_consensus_2.tsv, joint_post_2.tsv and clone_post_2.tsv from
#               data/amp1q/cnv/SubcloneDetection/<tumor_name>/ and mut_graph_2.rds from
#               data/amp1q/cnv/numbat_outs/<tumor_name>/.
# Dependencies: R with argparse, Seurat and numbat.
# ============================================================================

## command-line options
library(argparse)

parser <- ArgumentParser(description = "Run Numbat with count data")

## inputs
parser$add_argument("--countmat",
                    type = "character",
                    required = TRUE,
                    help = "Count matrix H5 file")
parser$add_argument("--alleledf",
                    type = "character",
                    required = TRUE,
                    help = "Allele data generated by pileup_and_phase script")
parser$add_argument("--barcodes",
                    type = "character",
                    required = FALSE,
                    help = "Cell barcode file")
parser$add_argument("--outdir",
                    type = "character",
                    required = TRUE,
                    help = "Output directory")

## Numbat parameters
parser$add_argument("--refexpr",
                    type = "character",
                    required = FALSE,
                    default = "NA",
                    help = "Reference expression profile")
parser$add_argument("--mincell",
                    type = "integer",
                    required = FALSE,
                    default = 50,
                    help = "Minimum number of cells to run HMM on (default=%(default)s)")
parser$add_argument("--tau",
                    type = "double",
                    required = FALSE,
                    default = 0.3,
                    help = "Factor to determine max_cost (= num cell * tau) as a function of the number of cells")
parser$add_argument("--tp",
                    type = "double",
                    required = FALSE,
                    default = 1e-5,
                    help = "Transition probability used in the HMM (default=%(default)s)")
parser$add_argument("--maxiter",
                    type = "integer",
                    required = FALSE,
                    default = 2,
                    help = "Maximum number of iterations (default=%(default)s)")
parser$add_argument("--minllr",
                    type = "integer",
                    required = FALSE,
                    default = 5,
                    help = "Minimum log-likelihood ratio threshold to filter CNVs (default=%(default)s)")
parser$add_argument("--initk",
                    type = "integer",
                    required = FALSE,
                    default = 2,
                    help = "Number of clusters in the initial clustering (default=%(default)s)")
parser$add_argument("--maxentropy",
                    type = "double",
                    required = FALSE,
                    default = 0.5,
                    help = "Entropy threshold to filter CNVs (default=%(default)s)")
parser$add_argument("--gamma",
                    type = "integer",
                    required = FALSE,
                    default = 20,
                    help = "Dispersion parameter for the Beta-Binomial allele model (default=%(default)s)")
parser$add_argument("--mindepth",
                    type = "integer",
                    required = FALSE,
                    default = 0,
                    help = "Minimum allele depth (default=%(default)s)")
parser$add_argument("--ncores",
                    type = "integer",
                    required = FALSE,
                    default = 8,
                    help = "Number of threads to use (default=%(default)s)")

args <- parser$parse_args()

## load data
suppressPackageStartupMessages({
  library(Seurat)
  library(numbat)
})

# count matrix, optionally restricted to the supplied barcodes
cat("Loading data\n")
df_count <- Read10X_h5(args$countmat)

if (!is.null(args$barcodes)) {
  if (file.exists(args$barcodes)) {
    cat("Subsetting count matrix with supplied barcodes\n")
    bc_list <- as.character(read.table(args$barcodes)[, 1])
    h5_bc <- colnames(df_count)
    df_count <- df_count[, h5_bc[h5_bc %in% bc_list]]
  }
}
cat("Supplied number of cells: ", ncol(df_count), "\n")

# phased allele counts
df_allele <- read.table(args$alleledf, header = TRUE, sep = "\t")

# reference expression: Numbat's ref_hca unless an RDS file is supplied
df_ref <- ref_hca
refexpr_stats <- "ref_hca in numbat"
if (file.exists(args$refexpr)) {
  df_ref <- readRDS(args$refexpr)
  refexpr_stats <- paste0("user supplied ", args$refexpr)
}
cat("Reference expression file: ", refexpr_stats, "\n")

## run Numbat
cat("Running Numbat\n")
run_numbat(
  df_count,
  df_ref,
  df_allele,
  genome      = "hg38",
  out_dir     = args$outdir,
  max_iter    = args$maxiter,
  t           = args$tp,
  gamma       = args$gamma,
  min_LLR     = args$minllr,
  max_entropy = args$maxentropy,
  init_k      = args$initk,
  min_cells   = args$mincell,
  tau         = args$tau,
  min_depth   = args$mindepth,
  ncores      = args$ncores,
  plot        = TRUE
)
